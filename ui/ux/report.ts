// Turns the journeys' JSON into ux-report/REPORT.md: a verdict per journey, a backlog of missing
// features, broken and slow steps, and screen-level findings grouped by rule (deduplicated across
// screens). Written so the user can read it without Claude: each finding says why it matters.
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { OUT, type JourneyResult, type StepResult } from "./harness";

const WHY: Record<string, string> = {
  "window-scrollbars": "the whole window scrolls — something overflows the layout (looks broken, the user reported this before)",
  "unlabeled-control": "an icon-only control with no tooltip: the user cannot tell what it does",
  "small-target": "hard to hit with a mouse or a stylus",
  "faint-icon": "icon too faint to see against its background (user reported faint icons)",
  "low-contrast-text": "text too faint to read comfortably",
  "tiny-text": "text below ~10.5 px",
  "clipped-text": "text is cut off with no ellipsis, so the user cannot tell it is truncated",
  "native-select": "a native dropdown: in the desktop app it opens as a light, unthemed GTK list (user reported this)",
};

const icon = (s: StepResult["status"]) =>
  ({ ok: "✅", slow: "🐢", broken: "❌", missing: "➖", present: "🎉", skipped: "⏭" })[s];

export default function report() {
  const dir = join(OUT, "results");
  if (!existsSync(dir)) return;
  const journeys: JourneyResult[] = readdirSync(dir).filter((f) => f.endsWith(".json")).sort()
    .map((f) => JSON.parse(readFileSync(join(dir, f), "utf8")));
  const steps = journeys.flatMap((j) => j.steps.map((s) => ({ j, s })));
  const count = (st: string) => steps.filter(({ s }) => s.status === st).length;
  const L: string[] = [];
  const meta = existsSync(join(OUT, "workspace.json")) ? JSON.parse(readFileSync(join(OUT, "workspace.json"), "utf8")) : null;

  L.push(`# Atlas UX audit — ${new Date().toISOString().slice(0, 16).replace("T", " ")}`, "");
  L.push("Generated by `npm run ux` (ui/ux/). Journeys act like a user on a copy of the real workspace;");
  L.push("every step is timed (time spent waiting on Atlas, typing excluded), screenshotted (`shots/`) and audited. Status: ✅ ok · 🐢 slower than its budget ·");
  L.push("❌ broken (Atlas has the feature, the step failed) · ➖ missing (a user would expect it) · 🎉 a wanted feature now exists.", "");
  if (meta) L.push(`Workspace: copy of \`${meta.source}\` — ${meta.notes.join("; ")}.`, "");
  L.push(`**${steps.length} steps** in ${journeys.length} journeys: ${count("ok")} ok, ${count("slow")} slow, ${count("broken")} broken, ${count("missing")} missing, ${count("present")} newly present, ${count("skipped")} skipped.`, "");

  // coverage: the app's own inventory minus what any journey touched
  const inv = existsSync(join(OUT, "inventory.json")) ? JSON.parse(readFileSync(join(OUT, "inventory.json"), "utf8")) : null;
  if (inv) {
    const kinds = new Set(journeys.flatMap((j) => j.kinds ?? []));
    const ran = new Set(journeys.flatMap((j) => j.commands ?? []));
    const deadKinds = (inv.paneKinds as string[]).filter((k) => !kinds.has(k));
    const notRun = (inv.commands as { id: string; title: string }[]).filter((c) => !ran.has(c.id));
    L.push("## Coverage", "");
    L.push(`- Pane kinds opened: ${kinds.size} of ${inv.paneKinds.length}${deadKinds.length ? ` — never opened: ${deadKinds.map((k) => `\`${k}\``).join(", ")}` : " (all)"}`);
    L.push(`- Commands run: ${inv.commands.length - notRun.length} of ${inv.commands.length}${notRun.length ? ` — not run: ${notRun.map((c) => `${c.title} (\`${c.id}\`)`).join(", ")}` : " (all)"}`);
    const skipped = steps.filter(({ s }) => s.status === "skipped");
    if (skipped.length) L.push(`- Skipped on purpose: ${skipped.map(({ s }) => `${s.name} — ${s.why}`).join("; ")}`);
    L.push("");
  }

  const missing = steps.filter(({ s }) => s.status === "missing");
  if (missing.length) {
    L.push("## Missing (what a user would need next)", "");
    for (const { j, s } of missing) L.push(`- **${s.name}** — ${s.why ?? ""} _(journey: ${j.name})_`);
    L.push("");
  }
  const broken = steps.filter(({ s }) => s.status === "broken");
  if (broken.length) {
    L.push("## Broken", "");
    for (const { j, s } of broken) L.push(`- **${j.name} › ${s.name}** — \`${s.error}\` ([screen](shots/${s.shot}))`);
    L.push("");
  }
  const slow = steps.filter(({ s }) => s.status === "slow");
  if (slow.length) {
    L.push("## Slow", "");
    for (const { j, s } of slow) L.push(`- **${j.name} › ${s.name}** — ${s.ms} ms (budget ${s.budget} ms)`);
    L.push("");
  }
  const errs = steps.filter(({ s }) => s.console.length);
  if (errs.length) {
    L.push("## Errors seen while using it", "");
    for (const { j, s } of errs) for (const c of [...new Set(s.console)]) L.push(`- ${j.name} › ${s.name}: \`${c}\``);
    L.push("");
  }

  // screen findings, deduplicated by rule + target across all screens
  const byRule = new Map<string, Map<string, string>>();
  for (const { s } of steps) for (const f of s.findings) {
    const m = byRule.get(f.rule) ?? new Map<string, string>();
    if (!m.has(f.target)) m.set(f.target, f.detail);
    byRule.set(f.rule, m);
  }
  if (byRule.size) {
    L.push("## Screen findings", "");
    for (const [rule, m] of [...byRule].sort((a, b) => b[1].size - a[1].size)) {
      L.push(`### ${rule} — ${m.size}`, "", `_${WHY[rule] ?? ""}_`, "");
      for (const [t, d] of [...m].slice(0, 12)) L.push(`- ${t} — ${d}`);
      if (m.size > 12) L.push(`- … and ${m.size - 12} more`);
      L.push("");
    }
  }

  L.push("## Journeys", "");
  for (const j of journeys) {
    const keys = j.steps.reduce((a, s) => a + s.keys, 0), clicks = j.steps.reduce((a, s) => a + s.clicks, 0);
    L.push(`### ${j.name}`, "", `_${j.goal}_ — ${keys} keys, ${clicks} clicks in total.`, "");
    L.push("| | step | wait | keys | clicks | screen |", "|---|---|---:|---:|---:|---|");
    for (const s of j.steps) L.push(`| ${icon(s.status)} | ${s.name}${s.error && s.status === "broken" ? ` — ${s.error.slice(0, 80)}` : ""} | ${s.ms} ms | ${s.keys} | ${s.clicks} | ${s.shot ? `[png](shots/${s.shot})` : ""} |`);
    L.push("");
  }
  writeFileSync(join(OUT, "REPORT.md"), L.join("\n"));
  console.log(`UX report: ${join(OUT, "REPORT.md")}`);
}
