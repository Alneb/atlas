#!/usr/bin/env bash
# The native plugins built into the Atlas apps (docs/refactor/REFACTOR-native-plugins.md): every plugins/<tier>/<id>/
# whose plugin.toml has an [android] table with `main`. Prints their Java source folders on stdout, and writes
# NativePlugins.java (the list the app reads) to the file given.
#   bash crates/atlas-android/native-plugins.sh <out/NativePlugins.java>
set -euo pipefail
repo=$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)
out=$1
mains=() tomls=()
for toml in "$repo"/plugins/*/*/plugin.toml; do
  [ -f "$toml" ] || continue
  # `main` inside the [android] table (up to the next table)
  main=$(awk '{ line = $0; sub(/[ \t]*#.*/, "", line) } line ~ /^\[/ { inside = (line == "[android]") } inside && line ~ /^main *=/ { gsub(/.*= *"|".*/, "", line); print line; exit }' "$toml")
  [ -n "$main" ] || continue
  dir=$(dirname "$toml")/android
  [ -d "$dir" ] || { echo "[native-plugins] $toml names $main but has no android/ folder" >&2; exit 1; }
  echo "$dir"
  mains+=("$main") tomls+=("$toml")
  echo "[native-plugins] $(basename "$(dirname "$toml")"): $main" >&2
done
{
  echo "package org.atlas.capture;"
  echo "/** Generated by crates/atlas-android/native-plugins.sh from the plugins' [android] tables: do not edit. */"
  echo "final class NativePlugins {"
  echo "    private NativePlugins() {}"
  echo "    static final NativePlugin[] ALL = {"
  for m in "${mains[@]+"${mains[@]}"}"; do echo "        new $m(),"; done
  echo "    };"
  echo "    static NativePlugin byId(String id) { for (NativePlugin p : ALL) if (p.id().equals(id)) return p; return null; }"
  # each one's plugin.toml, as the app adds it to a vault that lacks it (its settings are then the vault's, as any plugin's)
  echo '    /** The plugin.toml of built-in plugin `id` (its folder'"'"'s name), or null. */'
  echo "    static String manifest(String id) {"
  echo "        switch (id) {"
  for t in "${tomls[@]+"${tomls[@]}"}"; do
    echo "            case \"$(basename "$(dirname "$t")")\": return \"\"\""
    sed -e 's/\\/\\\\/g' -e 's/"""/\\"""/g' "$t"
    echo "\"\"\";"
  done
  echo "            default: return null;"
  echo "        }"
  echo "    }"
  # each one's shared/ files: the plugin's web code its native side uses too (one implementation: books' marks.js)
  echo '    /** File `name` of built-in plugin `id`'"'"'s shared/ folder, or null. */'
  echo "    static String shared(String id, String name) {"
  echo "        switch (id + \"/\" + name) {"
  for t in "${tomls[@]+"${tomls[@]}"}"; do
    for f in "$(dirname "$t")"/shared/*; do
      [ -f "$f" ] || continue
      echo "            case \"$(basename "$(dirname "$t")")/$(basename "$f")\": return \"\"\""
      sed -e 's/\\/\\\\/g' -e 's/"""/\\"""/g' "$f"
      echo "\"\"\";"
    done
  done
  echo "            default: return null;"
  echo "        }"
  echo "    }"
  echo "}"
} > "$out"
