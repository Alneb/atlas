"""Generate a BibTeX file from the references in <refs>/* (their notes' properties: ref_entry.py). Derived output:
never edit refs.bib by hand.
Usage: refs_bib.py REFS_DIR OUT.bib
"""
from __future__ import annotations
import re, sys
from pathlib import Path
import yaml  # noqa: F401  (ref_entry's)
sys.path.insert(0, str(Path(__file__).resolve().parent))
import ref_entry  # noqa: E402

KIND = {"journalArticle": "article", "book": "book", "bookSection": "incollection", "thesis": "phdthesis",
        "conferencePaper": "inproceedings", "preprint": "misc", "report": "techreport", "manuscript": "unpublished"}
FIELD = {"title": "title", "publicationTitle": "journal", "volume": "volume", "issue": "number",
         "pages": "pages", "publisher": "publisher", "place": "address", "DOI": "doi", "url": "url",
         "ISBN": "isbn", "ISSN": "issn", "university": "school", "series": "series", "edition": "edition",
         "bookTitle": "booktitle", "proceedingsTitle": "booktitle", "archiveID": "eprint", "repository": "publisher"}

def esc(v) -> str:
    return str(v).replace("&", r"\&").replace("%", r"\%").replace("#", r"\#")

def main() -> int:
    refs, out = Path(sys.argv[1]), Path(sys.argv[2])
    entries = []
    for d in sorted(p for p in refs.iterdir() if p.is_dir()):
        m = ref_entry.read(d)
        if m is None:
            continue
        key = m.get("citekey") or d.name
        lines = [f"@{KIND.get(m.get('type'), 'misc')}{{{key},"]
        for role, bib in (("author", "author"), ("editor", "editor")):
            if m.get(role): lines.append(f"  {bib} = {{{' and '.join(m[role])}}},")
        if (y := re.search(r"\d{4}", str(m.get("date", "")))): lines.append(f"  year = {{{y[0]}}},")
        for k, b in FIELD.items():
            if m.get(k): lines.append(f"  {b} = {{{esc(m[k])}}},")
        lines.append("}")
        entries.append("\n".join(lines))
    out.write_text("% Generated by refs_bib.py from the references' notes — do not edit.\n\n" + "\n\n".join(entries) + "\n", encoding="utf-8")
    print(f"[bib] {len(entries)} entries → {out}", file=sys.stderr)
    return 0

if __name__ == "__main__":
    sys.exit(main())
