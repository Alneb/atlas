#!/usr/bin/env node
// A native plugin as its own app in the phone's launcher (docs/guides/PLUGIN-API.md, "Native side"; ANDROID.md,
// "A plugin's own launcher icon"): `[android] launcher = { label, icon, home }` in its plugin.toml becomes, in the full
// apps' manifest, an <activity> of its own — the label, an adaptive icon made of the app's icon `icon` on Atlas's tile,
// its own task (`taskAffinity`, so it shows as its own app in recents) — that opens the plugin's native place `home`
// in the same process, the same core and the vault in use (PluginActivity reads the plugin and the place from the
// entry's meta-data). Each entry needs a class of its own: an empty subclass in the generated PluginLaunchers.java.
//   node scripts/dev/android-launchers.mjs <manifest in> <manifest out> <res dir> <PluginLaunchers.java out>
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { pathToFileURL } from "node:url";

const log = (m) => console.error(`[android-launchers] ${m}`);

/** Where the generated entries go in the manifest (AndroidManifest.atlas.xml). */
export const MARKER = "<!-- plugin launchers (scripts/dev/android-launchers.mjs) -->";

/** `[android] launcher = { … }` of a plugin.toml: `{ label, icon, home }`, or null when it has none. Throws when one is
 *  there but malformed (a wrong manifest fails the build, not the phone). */
export function launcherOf(text) {
  let inside = false;
  for (const raw of String(text).split("\n")) {
    const line = raw.replace(/\s+#.*$/, "").trim();
    const table = line.match(/^\[([^\]]+)\]$/);
    if (table) { inside = table[1].trim() === "android"; continue; }
    if (!inside) continue;
    const m = line.match(/^launcher\s*=\s*\{(.*)\}$/);
    if (!m) continue;
    const fields = {};
    for (const f of m[1].matchAll(/([a-z]+)\s*=\s*"([^"]*)"/g)) fields[f[1]] = f[2];
    for (const k of ["label", "icon", "home"]) if (!fields[k]) throw new Error(`[android] launcher has no ${k}: ${line}`);
    if (!/^[a-z_]+$/.test(fields.icon)) throw new Error(`[android] launcher icon must be one of the app's icon names (ic_<name>): ${fields.icon}`);
    return { label: fields.label, icon: fields.icon, home: fields.home };
  }
  return null;
}

const xml = (s) => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
/** A plugin id as a Java identifier and a resource name (`my-plugin` → `my_plugin`). */
export const javaName = (id) => id.replace(/[^A-Za-z0-9_]/g, "_");

/** The manifest's entries for the launchers ({ id, label, icon, home } each). */
export function manifestFragment(entries) {
  return entries.map((e) => {
    const n = javaName(e.id);
    return [
      `    <!-- ${xml(e.label)}: plugin ${xml(e.id)} as its own app (its own task in recents), on its native place ${xml(e.home)} -->`,
      `    <activity android:name="org.atlas.capture.PluginLaunchers$${n}" android:label="${xml(e.label)}" android:icon="@mipmap/ic_plugin_${n}" android:roundIcon="@mipmap/ic_plugin_${n}"`,
      `        android:taskAffinity="org.atlas.plugin.${n}" android:exported="true" android:theme="@style/App" android:enableOnBackInvokedCallback="true" android:configChanges="orientation|screenSize|screenLayout|smallestScreenSize|keyboardHidden">`,
      `      <intent-filter>`,
      `        <action android:name="android.intent.action.MAIN" />`,
      `        <category android:name="android.intent.category.LAUNCHER" />`,
      `      </intent-filter>`,
      `      <meta-data android:name="org.atlas.plugin" android:value="${xml(e.id)}" />`,
      `      <meta-data android:name="org.atlas.path" android:value="${xml(e.home)}" />`,
      `    </activity>`,
    ].join("\n");
  }).join("\n");
}

/** The adaptive icon of an entry: the app's icon (white strokes, android-res) inside the safe zone, on Atlas's tile. */
export function adaptiveIcon(e) {
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- ${xml(e.label)}'s launcher icon (scripts/dev/android-launchers.mjs): the app's icon ${xml(e.icon)} on Atlas's tile -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
  <background android:drawable="@drawable/ic_launcher_bg" />
  <foreground><inset android:drawable="@drawable/ic_${e.icon}" android:inset="30%" /></foreground>
  <monochrome><inset android:drawable="@drawable/ic_${e.icon}" android:inset="30%" /></monochrome>
</adaptive-icon>
`;
}

/** The classes the entries name: empty PluginActivity subclasses (an activity of its own per launcher). */
export function javaClasses(entries) {
  return `package org.atlas.capture;
/** Generated by scripts/dev/android-launchers.mjs from the plugins' \`[android] launcher\`: do not edit. Each one is a
 *  launcher entry of its own (its own task); PluginActivity reads the plugin and the place from its meta-data. */
public final class PluginLaunchers {
    private PluginLaunchers() {}
${entries.map((e) => `    public static final class ${javaName(e.id)} extends PluginActivity {}`).join("\n")}
}
`;
}

/** `manifest` with the fragment at its marker (which must be there exactly once). */
export function withLaunchers(manifest, entries) {
  const parts = manifest.split(MARKER);
  if (parts.length !== 2) throw new Error(`the manifest must hold ${MARKER} exactly once`);
  return parts[0] + MARKER + (entries.length ? "\n" + manifestFragment(entries) : "") + parts[1];
}

/** Every plugin's launcher, by id. */
export async function entries() {
  const { plugins } = await import("./plugin-files.mjs");
  const out = [];
  for (const p of plugins()) {
    const l = launcherOf(readFileSync(join(p.dir, "plugin.toml"), "utf8"));
    if (l) out.push({ id: p.id, ...l });
  }
  return out;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  const [inManifest, outManifest, resDir, javaOut] = process.argv.slice(2);
  if (!javaOut) { console.error("usage: android-launchers.mjs <manifest in> <manifest out> <res dir> <PluginLaunchers.java out>"); process.exit(2); }
  const all = await entries();
  writeFileSync(outManifest, withLaunchers(readFileSync(inManifest, "utf8"), all));
  mkdirSync(join(resDir, "mipmap-anydpi-v26"), { recursive: true });
  for (const e of all) writeFileSync(join(resDir, "mipmap-anydpi-v26", `ic_plugin_${javaName(e.id)}.xml`), adaptiveIcon(e));
  writeFileSync(javaOut, javaClasses(all));
  for (const e of all) log(`${e.id}: “${e.label}” (ic_${e.icon}) → ${e.home}`);
}
